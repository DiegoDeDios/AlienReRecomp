#!/usr/bin/env python3
"""Compile the renderer's GLSL shaders (src/render/shaders/*.vert|frag) for
every SDL GPU backend and write src/render/shaders_gen.h:

  SPIR-V  (Vulkan)       glslangValidator
  HLSL    (Direct3D 12)  spirv-cross, compiled to DXBC at run time
  MSL     (Metal)        spirv-cross

The generated header is committed, so building the port does not need
these tools; run this script after editing a shader:

  python3 tools/compile_shaders.py
"""
import os
import subprocess
import sys
import tempfile

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
SRC = os.path.join(ROOT, 'src', 'render', 'shaders')
OUT = os.path.join(ROOT, 'src', 'render', 'shaders_gen.h')
SHADERS = ['draw.vert', 'draw.frag', 'blit.vert', 'blit.frag', 'disp.vert', 'disp.frag']


def run(*cmd):
    r = subprocess.run(cmd, capture_output=True, text=True)
    if r.returncode != 0:
        sys.exit('%s failed:\n%s%s' % (cmd[0], r.stdout, r.stderr))
    return r.stdout


def c_string(text):
    lines = []
    for line in text.splitlines():
        line = line.replace('\\', '\\\\').replace('"', '\\"')
        lines.append('    "%s\\n"' % line)
    return '\n'.join(lines)


def c_bytes(data):
    rows = []
    for i in range(0, len(data), 16):
        rows.append('    ' + ', '.join('0x%02x' % b for b in data[i:i + 16]) + ',')
    return '\n'.join(rows)


def main():
    out = ['/* Generated by tools/compile_shaders.py from src/render/shaders/ - do not edit. */',
           '#pragma once',
           '#include "shader_blob.h"',
           '']
    with tempfile.TemporaryDirectory() as tmp:
        for name in SHADERS:
            src = os.path.join(SRC, name)
            spv = os.path.join(tmp, name + '.spv')
            run('glslangValidator', '-V', '--target-env', 'vulkan1.0', '-I' + SRC, '-o', spv, src)
            hlsl = run('spirv-cross', spv, '--hlsl', '--shader-model', '51')
            msl = run('spirv-cross', spv, '--msl', '--msl-version', '20100')
            data = open(spv, 'rb').read()
            ident = 'k_' + name.replace('.', '_')
            out += ['static const unsigned char %s_spirv[] = {' % ident, c_bytes(data), '};',
                    'static const char %s_hlsl[] =' % ident, c_string(hlsl) + ';',
                    'static const char %s_msl[] =' % ident, c_string(msl) + ';',
                    'static const ShaderBlob %s = {%s_spirv, sizeof %s_spirv, %s_hlsl, %s_msl};'
                    % (ident, ident, ident, ident, ident),
                    '']
    with open(OUT, 'w') as f:
        f.write('\n'.join(out))
    print('wrote', os.path.relpath(OUT, ROOT))


if __name__ == '__main__':
    main()
